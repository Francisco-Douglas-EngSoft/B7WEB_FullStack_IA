//Existe algumas formas de cria variaveis
let nome = "Lucas"; //Forma mais moderna de criar variaveis
var idade = 20; //Forma mais antiga de criar variaveis
const cidade = "São Paulo"; //Forma de criar variaveis que não podem ser alteradas

//Cada forma de criar variaveis tem suas particularidades, por exemplo, a variavel criada com var pode ser redeclarada e alterada, enquanto a variavel criada com let pode ser alterada mas não redeclarada, e a variavel criada com const não pode ser nem alterada nem redeclarada.